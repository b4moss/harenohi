import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const projectRoot = path.join(__dirname, '..')

const sourceCsvPath = path.join(
  projectRoot,
  'src',
  'data',
  'jp-holiday',
  'source',
  'syukujitsu.csv'
)
const overrideDir = path.join(projectRoot, 'src', 'data', 'jp-holiday', 'override')
const mapOutPath = path.join(projectRoot, 'src', 'data', 'jp-holiday', 'override-map.ts')

/**
 * CSV 1行をパースし、年と Holiday を返す。
 * 空行・不正行は null（スキップ）。
 */
export function parseLine(line) {
  const trimmed = line.trim()
  if (!trimmed) return null
  const [rawDate, rawTitle] = trimmed.split(',')
  if (!rawDate || !rawTitle) return null

  const [y, m, d] = rawDate.split('/')
  if (!y || !m || !d) return null

  const year = Number(y)
  if (!Number.isInteger(year)) return null

  const mm = String(Number(m)).padStart(2, '0')
  const dd = String(Number(d)).padStart(2, '0')
  if (Number(m) < 1 || Number(m) > 12 || Number(d) < 1 || Number(d) > 31) return null

  const date = `${y}-${mm}-${dd}`
  const title = rawTitle.trim()
  if (!title) return null

  return { year, entry: { title, date } }
}

/**
 * Shift_JIS または UTF-8 の CSV テキストを年別配列に変換する。
 * @param {string} csv
 * @returns {Record<number, { title: string; date: string }[]>}
 */
export function parseCsvText(csv) {
  const lines = csv.split(/\r?\n/)
  /** @type {Record<number, { title: string; date: string }[]>} */
  const byYear = {}

  // ヘッダ行をスキップ
  for (const line of lines.slice(1)) {
    const parsed = parseLine(line)
    if (!parsed) continue
    const { year, entry } = parsed
    if (!byYear[year]) byYear[year] = []
    byYear[year].push(entry)
  }

  for (const year of Object.keys(byYear)) {
    byYear[Number(year)].sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0))
  }
  return byYear
}

export function decodeCsvBuffer(buf) {
  try {
    const decoded = new TextDecoder('shift_jis').decode(buf)
    if (decoded.includes('国民の祝日') || decoded.includes('元日')) return decoded
  } catch {
    // fall through
  }
  return buf.toString('utf8')
}

function writeOverrideMap(byYear) {
  const years = Object.keys(byYear)
    .map(Number)
    .filter((y) => Number.isInteger(y))
    .sort((a, b) => a - b)

  const lines = [
    '/* Generated by scripts/parse-jp-holiday-csv.mjs — do not edit by hand. */',
    "import type { HolidayList } from '../../types.js'",
    '',
    'export const overrideByYear: Record<number, HolidayList> = {',
  ]

  for (const year of years) {
    const json = JSON.stringify(byYear[year], null, 2)
      .split('\n')
      .map((line, i) => (i === 0 ? line : `  ${line}`))
      .join('\n')
    lines.push(`  ${year}: ${json},`)
  }

  lines.push('}', '')
  fs.writeFileSync(mapOutPath, `${lines.join('\n')}\n`, 'utf8')
  console.log(`wrote ${mapOutPath} (${years.length} years)`)
}

export function writeOverrides(byYear) {
  fs.mkdirSync(overrideDir, { recursive: true })
  const years = Object.keys(byYear)
    .map(Number)
    .filter((y) => Number.isInteger(y))
    .sort((a, b) => a - b)

  for (const year of years) {
    const list = byYear[year] || []
    const outPath = path.join(overrideDir, `${year}.json`)
    fs.writeFileSync(outPath, `${JSON.stringify(list, null, 2)}\n`, 'utf8')
    console.log(`wrote ${outPath} (${list.length} holidays)`)
  }
  writeOverrideMap(byYear)
  return years
}

function main() {
  if (!fs.existsSync(sourceCsvPath)) {
    console.error(`CSV file not found: ${sourceCsvPath}`)
    process.exit(1)
  }
  const buf = fs.readFileSync(sourceCsvPath)
  const csv = decodeCsvBuffer(buf)
  const byYear = parseCsvText(csv)
  const years = writeOverrides(byYear)
  if (years.length === 0) {
    console.error('No holiday years parsed from CSV')
    process.exit(1)
  }
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href

if (isMain) {
  main()
}
